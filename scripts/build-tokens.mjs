// 从 scripts/tokens/source.mjs 生成各消费端的 token 产物（ADR 0046）。
// 用法：npm run build:tokens。改值只改源，然后重跑；每份产物的新鲜度由各自的单测守（产物 = 本生成器输出）。
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SEMANTIC, STATUS, FONT, RADIUS, FONT_SIZE, LINE_HEIGHT, SHADOW, PROSE } from './tokens/source.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HEAD = (what) => `/* GENERATED by scripts/build-tokens.mjs from scripts/tokens/source.mjs — 手改无效，改源后 npm run build:tokens。
 * ${what} */\n`;

/** 亮暗三段：默认亮；系统暗且没手动选亮；手动选暗。站点、图 kit 共用这个形状（data-theme 是站点的深浅色开关）。 */
function threeSegments(lightDecl, darkDecl, indent = '  ') {
  const block = (decl) => decl.map((d) => indent + d).join('\n');
  return `:root {\n${block(lightDecl)}\n  color-scheme: light;\n}\n`
    + `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${block(darkDecl).replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }\n}\n`
    + `:root[data-theme="dark"] {\n${block(darkDecl)}\n  color-scheme: dark;\n}\n`;
}

// ---------- 站点：site/src/styles/tokens.css ----------
export function buildSiteTokensCss() {
  const color = (mode) => [
    ...Object.entries(SEMANTIC).map(([k, v]) => `--pp-${k}:${v[mode]};`),
    ...Object.entries(STATUS).flatMap(([k, v]) => [`--pp-status-${k}:${v.bg[mode]};`, `--pp-status-${k}-fg:${v.fg[mode]};`]),
    ...Object.entries(SHADOW).map(([k, v]) => `--pp-sh-${k}:${v[mode]};`),
    `--pp-scrim:${mode === 'light' ? 'rgba(17,17,17,.56)' : 'rgba(0,0,0,.72)'};`,
  ];
  const geometry = [
    `--pp-font:${FONT.sans};`,
    `--pp-font-mono:${FONT.mono};`,
    ...Object.entries(RADIUS).map(([k, [v, use]]) => `--pp-r-${k}:${v}; /* ${use} */`),
    ...Object.entries(FONT_SIZE).map(([k, v]) => `--pp-fs-${k}:${v};`),
    ...Object.entries(LINE_HEIGHT).map(([k, v]) => `--pp-lh-${k}:${v};`),
    '--pp-space:4px; /* 间距基数：calc(var(--pp-space) * n) */',
    ...Object.entries(PROSE).map(([k, [v, use]]) => `--pp-prose-${k}:${v}; /* ${use} */`),
  ];
  return HEAD('文章站点的 --pp-* token：语义色（亮暗三段）+ 几何与排印。site/src/layouts/Base.astro 引入。')
    + `:root {\n${geometry.map((d) => '  ' + d).join('\n')}\n}\n`
    + threeSegments(color('light'), color('dark'));
}

export const TARGETS = {
  'site/src/styles/tokens.css': buildSiteTokensCss,
};

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  for (const [rel, build] of Object.entries(TARGETS)) {
    writeFileSync(path.join(ROOT, rel), build());
    console.log('written', rel);
  }
}
