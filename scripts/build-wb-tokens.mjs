// 生成 workbench/wb-tokens.css —— workbench chrome 视觉 token 的单一事实源。
// 用法：npm run build:tokens。改 token 只改本文件然后重跑；
// workbench/wb-tokens.test.js 守鲜度（磁盘文件与本生成器输出逐字节一致）。
//
// 色值两路来源（goal-20260810-workbench-react-rebuild P4 决策）：
//  - 与 Radix Colors 刻度差 ≤1 档的中性色锚定刻度（@radix-ui/colors，构建期
//    普通 JS 引用，值直接取自包，provenance 可查）—— 归并进阶梯时锚定；
//  - 产品调好的值写字面量并注由来。--wb-accent 是 iOS 蓝 #007aff，锁定不漂移。
// 归一对象是散装阶梯（radius/font-weight/shadow/danger），不是换调色板。
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gray, slate } from '@radix-ui/colors';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildWbTokensCss() {
  return `/* GENERATED by scripts/build-wb-tokens.mjs — 手改无效，改脚本后 npm run build:tokens。
 * workbench chrome 视觉 token（goal-20260810-workbench-react-rebuild P4）。
 * index.html <link> 本文件；注入端 client 在 #ann-sidebar 上钉同款取值
 * （client/annotate.js），ann-list.css 双端共享行样式经 var(--wb-*, 兜底) 消费。
 * 第二段 :root 是 shadcn 主题桥（goal-20260811-workbench-visual-rebuild V0）：
 * shadcn/Tailwind 语义变量 ← --wb-* 的唯一映射点，app/ui 组件里不许出现第二处色值源。 */
:root {
  /* ── 色：语义 token 保留原名，值锚 Radix 刻度或产品字面量 ── */
  --wb-bg:${slate.slate4}; /* Radix slate 4（原 #e8eaed，差 ≤1 档锚定） */
  --wb-side:#f6f6f7; /* 产品调（slate 2–3 正中间，保留原值） */
  --wb-fg:${slate.slate12}; /* Radix slate 12（原 iOS label #1c1c1e，差 ≤1 档锚定） */
  --wb-muted:#6b6b70; /* 产品调（gray/slate 11 之间，保留原值） */
  --wb-faint:${gray.gray9}; /* Radix gray 9（原 iOS systemGray #8e8e93，差 ≤1 档锚定） */
  --wb-line:rgba(0,0,0,.07); /* Radix blackA 粒度太粗（.05/.1/.15），保留产品 alpha */
  --wb-hover:rgba(0,0,0,.04);
  --wb-fill:rgba(0,0,0,.055);
  --wb-accent:#007aff; /* iOS 蓝 —— 产品视觉身份，锁定不漂移 */
  --wb-danger:#ff3b30; /* iOS systemRed —— danger 唯一源（原 #c0392b/#a33/rgba(192,57,43,*) 三写法归并） */
  --wb-stage-bg:#faf8f4; /* 画布暖纸色，产品调 */
  --wb-surface:#fff; /* chrome 纯白面（选中态/卡面/强调面上的文字）—— shadcn 桥需要时归并的起点 */

  /* ── 圆角阶梯（散装 14 档归并；999px/50% 是功能形状，不进阶梯） ── */
  --wb-r-1:4px;   /* 槽内小按钮、内联编辑底、迷你屏幕钮（吸收 2px —— 3px 宽条上渲染恒等） */
  --wb-r-2:6px;   /* 列表行、小控件（吸收 7px） */
  --wb-r-3:8px;   /* 卡片、菜单项、槽容器（吸收 9px） */
  --wb-r-4:12px;  /* 浮层面板、HUD、输入框（吸收 10/11/13px） */
  --wb-r-board:16px; /* 画布画板（吸收 14px） */
  --wb-r-dialog:20px; /* 模态对话框 —— 差异明显，保留命名 */

  /* ── 字重阶梯（散装 400/500/550/600/620/650/700 归并） ── */
  --wb-w-regular:400;
  --wb-w-medium:500;   /* 吸收 550 */
  --wb-w-semibold:600; /* 吸收 620/650 */
  --wb-w-bold:700;

  /* ── 阴影阶梯（散装散值归并；功能性 ring/描边不进阶梯） ── */
  --wb-sh-1:0 1px 2px rgba(0,0,0,.06), 0 0 0 0.5px rgba(0,0,0,.04); /* 选中凸起（分段钮等） */
  --wb-sh-2:0 1px 2px rgba(0,0,0,.06), 0 8px 24px rgba(0,0,0,.1);   /* 浮动 chrome（HUD） */
  --wb-sh-3:0 1px 2px rgba(0,0,0,.06), 0 14px 38px rgba(0,0,0,.16); /* 浮层面板（菜单/导航） */
  --wb-sh-4:0 28px 80px rgba(0,0,0,.24); /* 模态 */
  --wb-sh-line:inset 0 0 0 1px var(--wb-line); /* 发丝描边（与阶梯叠加或单用） */
  --wb-sh-board:0 1px 0 rgba(0,0,0,.04), 0 14px 40px rgba(0,0,0,.08); /* 画布画板纸面 */

  /* ── 字体栈（V1 新增：chrome 文字控件经 Tailwind --font-sans 消费） ── */
  --wb-font:-apple-system,BlinkMacSystemFont,"SF Pro Text","PingFang SC",system-ui,sans-serif; /* 产品字体栈，与 index.html body 一致（body 也改指本 token） */

  /* ── 结构 / 动效 ── */
  --wb-side-w:252px;
  --wb-pad:14px;
  --wb-ease:cubic-bezier(.25,0,0,1);
  --wb-dur:.2s;
}

/* ── shadcn 主题桥（V0）：语义变量全部引用 --wb-*，本段是唯一映射点 ──
 * Tailwind 侧在 workbench/app/wb-tw.css 的 @theme inline 里把 --color-* 与
 * --radius-* 解析到这里的变量；组件类名（bg-primary/text-muted-foreground/
 * border-border/rounded-md…）最终落到上面那段的 --wb-* 取值。 */
:root {
  --background:var(--wb-bg);
  --foreground:var(--wb-fg);
  --card:var(--wb-surface);          /* 卡面/选中面（分段钮 on 态 = #fff，产品现状） */
  --card-foreground:var(--wb-fg);
  --popover:var(--wb-side);          /* 浮层面（frame menu / export dialog 现取 --wb-side） */
  --popover-foreground:var(--wb-fg);
  --primary:var(--wb-accent);        /* #007aff 锁定 */
  --primary-foreground:var(--wb-surface);
  --secondary:var(--wb-fill);        /* 次级面 = 浅填充 */
  --secondary-foreground:var(--wb-fg);
  --muted:var(--wb-fill);            /* 哑面（toggle-group 容器等） */
  --muted-foreground:var(--wb-muted);
  --accent:var(--wb-hover);          /* shadcn accent = hover 浅面，不是产品 accent */
  --accent-foreground:var(--wb-fg);
  --destructive:var(--wb-danger);
  --destructive-foreground:var(--wb-surface);
  --border:var(--wb-line);           /* 发丝边 */
  --input:var(--wb-line);
  --ring:var(--wb-accent);           /* focus ring：accent，alpha 由类名 /50 或 color-mix 给 */
  --radius:var(--wb-r-2);            /* 基准圆角；阶梯经 wb-tw.css @theme 直挂 --wb-r-* */
}
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const target = path.join(ROOT, 'workbench', 'wb-tokens.css');
  writeFileSync(target, buildWbTokensCss());
  console.log('written', path.relative(ROOT, target));
}
